// The PIF answers immediately here: both SI transfers complete by posting to the SI queue.
extern "C" void cic_send_challenge(uint8_t* rdram, recomp_context* ctx) {
    gpr challenge = ctx->r4;
    gpr queue = ctx->r5;
    uint8_t in[30];
    uint8_t out[30];

    for (int i = 0; i < 15; i++) {
        uint8_t byte = MEM_B(i, challenge);
        in[i * 2] = byte >> 4;
        in[i * 2 + 1] = byte & 0xF;
    }
    bt_cic6105(in, out, 30);
    for (int i = 0; i < 15; i++) {
        MEM_B(0x30 + i, cic_buffer) = (out[i * 2] << 4) | out[i * 2 + 1];
    }
    MEM_B(0x2E, cic_buffer) = 0;
    MEM_B(0x2F, cic_buffer) = 0;
    MEM_B(0x3F, cic_buffer) = 0;
    send_empty_message(rdram, ctx, queue);
}

extern "C" void cic_read_response(uint8_t* rdram, recomp_context* ctx) {
    send_empty_message(rdram, ctx, ctx->r4);
}

