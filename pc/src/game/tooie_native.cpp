void tooie::on_init(uint8_t* rdram, recomp_context* ctx) {
    MEM_W(0, sext(0x80000310)) = 6105;

    // Register reads and ROM reads through K1 stay plain memory accesses. Zeroes satisfy the PI
    // busy polls, and the mirror serves the reads that decrypt overlay relocations.
    std::span<const uint8_t> rom = recomp::get_rom();
    if (mprotect(rdram + io_window_offset, io_window_size, PROT_READ | PROT_WRITE) != 0) {
        perror("mprotect");
        std::exit(EXIT_FAILURE);
    }
    for (size_t i = 0; i < rom.size() && i < io_window_size - (rom_mirror_offset - io_window_offset); i++) {
        rdram[rom_mirror_offset + (i ^ 3)] = rom[i];
    }

    // Leftovers of IPL3 that func_8001DE64 checks for.
    MEM_W(0, sext(0xA02FB1F4)) = 0xAD090010;
    MEM_W(0, sext(0xA02FE1C0)) = 0xAD170014;

    // Compressed code is loaded by the game itself, so register the fixed segments up front.
    load_overlays(0x00001000, sext(0x80000400), 0x000040E0);
    load_overlays(0x01E29B60, sext(0x80012030), 0x00031350);
    load_overlays(0x01E5AEB0, sext(0x800815C0), 0x000A5170);
}

// Every overlay entrypoint is a table slot starting with `syscall`. On hardware the exception jumps to
// syscall_handler, which loads the overlay and rewrites the slots to `j hook`. The hook copied to
// overlay + 0x10 then either enters the function or, for run-once overlays, calls it and unloads.
extern "C" void recomp_syscall_handler(uint8_t* rdram, recomp_context* ctx, int32_t instruction_vram) {
    gpr slot = (gpr)instruction_vram;
    uint32_t word = MEM_W(0, slot);

    if ((word & 0xFC00003F) == 0xC) {
        ctx->r8 = slot;
        // Ends with `jr t0`, which re-enters this slot after it was rewritten.
        syscall_handler(rdram, ctx);
        return;
    }

    gpr hook = sext(((word & 0x03FFFFFF) << 2) | 0x80000000);
    gpr overlay = hook - 0x10;
    uint32_t hook_word = MEM_W(0, hook);

    if ((hook_word >> 26) == 3) { // jal: run-once hook from ovl_entrypoint_alternate
        LOOKUP_FUNC(sext(((hook_word & 0x03FFFFFF) << 2) | 0x80000000))(rdram, ctx);
        // func_80081E30 finds the overlay and the saved return address through ra.
        ctx->r31 = hook + 0x10;
        func_80081E30(rdram, ctx);
        return;
    }

    uint32_t entry_offset = (uint16_t)MEM_H(6, slot);
    uint32_t target = MEM_W(0x38 + entry_offset, overlay);
    MEM_H(0x32, overlay) = 0; // Reset the idle age, like the hook's delay slot.
    LOOKUP_FUNC(sext(target))(rdram, ctx);
}

// Hook in func_80082088 after relocating: s2 is the text address, sp + 0x28 the overlay.
extern "C" void tooie_overlay_placed(uint8_t* rdram, recomp_context* ctx) {
    gpr overlay = (gpr)MEM_W(0x28, ctx->r29);
    int id = overlay_ids[(uint16_t)MEM_H(0x2C, overlay)];
    trace_ovl_loads++; // TRACE-TEMP
    unload_overlay_by_id(id);
    load_overlay_by_id(id, (uint32_t)ctx->r18);
}

// Hook at the start of ovl_reset_syscalls.
extern "C" void tooie_overlay_removed(uint8_t* rdram, recomp_context* ctx) {
    unload_overlay_by_id(overlay_ids[(uint16_t)MEM_H(0x2C, ctx->r4)]);
}

