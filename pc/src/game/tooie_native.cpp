// The scheduler treats a cleared IM5 bit as the reset button's pre-NMI interrupt.
extern "C" void __osGetSR_2(uint8_t* rdram, recomp_context* ctx) {
    ctx->r2 = 0x2000FF01;
}

// A task started while frozen would only run after func_8001443C thawed the RDP and copied the pending
// state. It finishes immediately here, so do that thaw now or the "frame done" bit is lost and the game hangs.
extern "C" void tooie_dp_complete(uint8_t* rdram, recomp_context* ctx) {
    constexpr uint32_t DPC_STATUS_FREEZE = 2, DPC_CLR_FREEZE = 4;
    tooie_trace(rdram, ctx, 4); // TRACE-TEMP
    osDpGetStatus_recomp(rdram, ctx);
    if (ctx->r2 & DPC_STATUS_FREEZE) {
        ctx->r4 = DPC_CLR_FREEZE;
        osDpSetStatus_recomp(rdram, ctx);
        MEM_W(0, sext(0x80078484)) = MEM_W(0, sext(0x80078488));
    }
}

// Fake but moving scanline, so busy-waits on the VI beam position terminate.
extern "C" void osViGetCurrentLine_recomp(uint8_t* rdram, recomp_context* ctx) {
    using namespace std::chrono;
    constexpr int64_t frame_us = 16683;
    int64_t us = duration_cast<microseconds>(steady_clock::now().time_since_epoch()).count();
    ctx->r2 = (us % frame_us) * 525 / frame_us;
}

// TRACE-TEMP
extern "C" void tooie_trace(uint8_t* rdram, recomp_context* ctx, int id) {
    static int counts[16];
    static auto last = std::chrono::steady_clock::now();
    counts[id]++;
    auto now = std::chrono::steady_clock::now();
    if (now - last > std::chrono::seconds(1)) {
        last = now;
        fprintf(stderr, "[rate] gfxmsg %d gfxstart %d sp %d dp %d wake %d vi %d aud %d ovl %d black %d d7913c %d\n", counts[1], counts[2], counts[3], counts[4], counts[5], counts[6], counts[7], trace_ovl_loads, MEM_W(0, sext(0x80079700)), MEM_W(0, sext(0x8007913C)));
        for (int& c : counts) c = 0;
        trace_ovl_loads = 0;
    }
}
