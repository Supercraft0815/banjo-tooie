constexpr gpr sext(uint32_t addr) {
    return (gpr)(int32_t)addr;
}

constexpr gpr cic_buffer = sext(0x8007D850);
constexpr uint32_t rom_mirror_offset = 0x30000000; // 0xB0000000 relative to rdram.
constexpr uint32_t io_window_offset = 0x20000000;  // 0xA0000000 relative to rdram.
constexpr uint32_t io_window_size = 0x20000000;


void send_empty_message(uint8_t* rdram, recomp_context* ctx, gpr queue) {
    ctx->r4 = queue;
    ctx->r5 = 0;
    ctx->r6 = 0; // OS_MESG_NOBLOCK
    osSendMesg_recomp(rdram, ctx);
}

