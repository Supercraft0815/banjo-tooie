"""Indirect calls whose target has another signature than the call site, the N64 way.

The game calls through function pointers with any declared signature: the arguments travel in
MIPS O32 registers, so a float passed as third argument reaches a callee that declares an int
there. wasm2c casts the pointer to the call site's type, which on a native ABI moves floats to
other registers than integers (subaddietaxi restore callbacks got flags for rotation). This
generates, per wasm function type, a packer for the call site and a caller for the target; on a
type mismatch CALL_INDIRECT goes through bt_o32_call, which maps arguments like the bt-fixcalls
pass does for direct calls (by position, or by register when a float and an integer swap
places in the first two arguments) and converts the result. BT_O32_LOG=1 lists each pair once.
"""
import re
import subprocess

C = {'i32': 'u32', 'i64': 'u64', 'f32': 'f32', 'f64': 'f64'}
TAG = {'i32': 'i', 'i64': 'l', 'f32': 'f', 'f64': 'd'}
FIELD = {'i32': 'i', 'i64': 'l', 'f32': 'f', 'f64': 'd'}

RUNTIME = r'''
typedef struct { char t; union { u32 i; u64 l; f32 f; f64 d; } v; } BtArg;  // t: i l f d, 0 = void
typedef struct {
    const char *const *id;  // wasm2c's type id variable
    const char *params;
    char ret;
    void (*call)(wasm_rt_function_ptr_t, void *, const BtArg *, BtArg *);
} BtType;
_Noreturn void bt_fatal(const char *fmt, ...);

// One register's value read as another type (bt-fixcalls convert()): floats keep their value
// between float types, everything else keeps its bits, sign-extended or truncated.
static BtArg conv(BtArg a, char to) {
    BtArg o = {.t = to};
    int ffrom = a.t == 'f' || a.t == 'd', fto = to == 'f' || to == 'd';
    s64 bits = 0;
    if (a.t == to || !to) return a;
    if (ffrom && fto) { if (to == 'd') o.v.d = a.v.f; else o.v.f = (f32)a.v.d; return o; }
    if (a.t == 'i') bits = (s32)a.v.i;
    else if (a.t == 'l') bits = (s64)a.v.l;
    else if (a.t == 'f') { s32 b; memcpy(&b, &a.v.f, 4); bits = b; }
    else if (a.t == 'd') memcpy(&bits, &a.v.d, 8);
    if (to == 'i') o.v.i = (u32)bits;
    else if (to == 'l') o.v.l = (u64)bits;
    else if (to == 'f') { u32 b = (u32)bits; memcpy(&o.v.f, &b, 4); }
    else memcpy(&o.v.d, &bits, 8);
    return o;
}

// MIPS O32 register of each parameter (o32Registers in FixCalls.cpp): 0..3 a0..a3, 12/14 f12/f14,
// 100+n stack slot n.
static void o32(const char *p, int *reg) {
    int slot = 0, all_float = 1;
    for (int i = 0; p[i]; i++) {
        int f = p[i] == 'f' || p[i] == 'd', words = p[i] == 'l' || p[i] == 'd' ? 2 : 1;
        if (words == 2) slot = (slot + 1) & ~1;
        reg[i] = f && i < 2 && all_float ? (i ? 14 : 12) : slot < 4 ? slot : 100 + slot;
        all_float &= f;
        slot += words;
    }
}

void bt_o32_call(const wasm_rt_funcref_t *e, int site, const BtArg *args, BtArg *ret) {
    static unsigned char seen[NTYPES][NTYPES];
    static int log = -1;
    const BtType *s = &TYPES[site], *t = NULL;
    int have[MAXP], regs[MAXP], ns = (int)strlen(s->params), nt, by_register = 0;
    BtArg vals[MAXP], r = {0};
    for (int i = 0; i < NTYPES && !t; i++)
        if (*TYPES[i].id == e->func_type) t = &TYPES[i];
    if (!t) bt_fatal("indirect call to a function of an unknown type");
    nt = (int)strlen(t->params);
    o32(s->params, have);
    o32(t->params, regs);
    for (int i = 0; i < 2 && i < nt && i < ns; i++)
        by_register |= (regs[i] >= 12 && regs[i] < 100) != (have[i] >= 12 && have[i] < 100);
    for (int i = 0; i < nt; i++) {
        int k = by_register ? -1 : i < ns ? i : -1;
        for (int j = 0; by_register && j < ns && k < 0; j++)
            if (have[j] == regs[i]) k = j;
        vals[i] = k >= 0 ? conv(args[k], t->params[i]) : (BtArg){.t = t->params[i]};
    }
    if (log < 0) log = getenv("BT_O32_LOG") != NULL;
    if (log && !seen[site][t - TYPES]) {
        seen[site][t - TYPES] = 1;
        fprintf(stderr, "bt_native o32: call (%s)%c reaches a function (%s)%c%s\n", s->params, s->ret ? s->ret : 'v',
                t->params, t->ret ? t->ret : 'v', by_register ? ", by register" : "");
    }
    t->call(e->func, e->module_instance, vals, &r);
    *ret = s->ret ? conv(r.t ? r : (BtArg){.t = 'i'}, s->ret) : r;
}
'''


def types(wasm, objdump='wasm-objdump'):
    text = subprocess.run([objdump, '-x', '-j', 'Type', str(wasm)], capture_output=True, text=True, check=True).stdout
    out = []
    for n, params, ret in re.findall(r'type\[(\d+)\] \(([^)]*)\) -> (\w+)', text):
        assert int(n) == len(out)
        out.append(([p.strip() for p in params.split(',') if p.strip()], None if ret == 'nil' else ret))
    return out


def generate(wasm, gen, prefix='w2c_bt_t'):
    """Writes gen/o32_thunks.h and gen/o32.c; returns the text CALL_INDIRECT is replaced with."""
    ts = types(wasm)
    head = ['// Generated by pc/native/wasm/o32_thunks.py.', '#ifndef BT_O32_THUNKS_H', '#define BT_O32_THUNKS_H']
    body = ['// Generated by pc/native/wasm/o32_thunks.py.', '#include <stdio.h>', '#include <stdlib.h>',
            '#include <string.h>', '#include "game.h"', '#include "game-impl.h"',
            '#define NTYPES %d' % len(ts), '#define MAXP %d' % max(1, max(len(p) for p, _ in ts)),
            '']
    callers, table, sites = [], [], []
    for n, (params, ret) in enumerate(ts):
        cret = C[ret] if ret else 'void'
        cparams = ''.join(', %s p%d' % (C[p], i) for i, p in enumerate(params))
        fn_type = '%s (*)(void *%s)' % (cret, ''.join(', ' + C[p] for p in params))
        call = '((%s)fn)(inst%s)' % (fn_type, ''.join(', a[%d].v.%s' % (i, FIELD[p]) for i, p in enumerate(params)))
        callers.append('static void callee_%d(wasm_rt_function_ptr_t fn, void *inst, const BtArg *a, BtArg *r) {\n'
                       '    (void)a; %s\n}' % (n, ("r->t = '%s'; r->v.%s = %s;" % (TAG[ret], FIELD[ret], call)) if ret
                                              else 'r->t = 0; %s;' % call))
        table.append('    {&%s%d, "%s", %s, callee_%d},' % (prefix, n, ''.join(TAG[p] for p in params),
                                                         "'%s'" % TAG[ret] if ret else '0', n))
        proto = '%s bt_site_%s%d(const wasm_rt_funcref_t *e, void *inst%s)' % (cret, prefix, n, cparams)
        head.append(proto + ';')
        packed = ', '.join("{'%s', .v.%s = p%d}" % (TAG[p], FIELD[p], i) for i, p in enumerate(params)) or '{0}'
        sites.append('%s {\n    BtArg a[] = {%s}, r;\n    (void)inst;\n    bt_o32_call(e, %d, a, &r);\n%s}'
                     % (proto, packed, n, '    return r.v.%s;\n' % FIELD[ret] if ret else ''))
    head.append('#endif')
    runtime = RUNTIME
    # the type table sits between the struct definitions and the dispatcher
    split = runtime.index('// One register')
    text = '\n'.join(body) + runtime[:split] + '\n'.join(callers) + '\nstatic const BtType TYPES[NTYPES] = {\n' + \
        '\n'.join(table) + '\n};\n\n' + runtime[split:] + '\n' + '\n'.join(sites) + '\n'
    return '\n'.join(head) + '\n', text


