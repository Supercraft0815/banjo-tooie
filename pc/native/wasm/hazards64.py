#!/usr/bin/env python3
"""Phase-5 work list: compile every game file for a 64-bit host (-fsyntax-only) and list the
places where pointers and 32-bit integers mix. Output: build/hazards64.tsv (file, line, flag,
message) and a per-flag / per-file summary on stdout.

  python3 pc/native/wasm/hazards64.py [--top 15]
"""
import argparse
import collections
from concurrent.futures import ThreadPoolExecutor
import os
import re
import subprocess

import build

# Same sources and macros as the ILP32 build, but LP64 (no BT_ILP32) and only these warnings.
WARNINGS = ['-Wpointer-to-int-cast', '-Wint-to-pointer-cast', '-Wshorten-64-to-32', '-Wint-conversion',
            '-Wvoid-pointer-to-int-cast', '-Wpointer-integer-compare']
FLAGS = [f for f in build.GUEST_FLAGS if f not in ('-DBT_ILP32=1', '-flto', '-w') and not f.startswith('--target')
         and not f.startswith('-Wno-int-conversion')]
FLAGS = ['--target=arm64-apple-macos13', '-fsyntax-only', '-Wno-everything'] + WARNINGS + FLAGS
FLAGS = [f for f in FLAGS if f not in ('-Xclang', '-disable-llvm-passes')]
PTRSIZED = re.compile(r"(?:passing|from|to|returning) '(?:BtIntPtr|BtUIntPtr|BtFnWord)'|type '(?:BtIntPtr|BtUIntPtr|BtFnWord)'")
LINE = re.compile(r'^(.+?):(\d+):\d+: warning: (.*) \[(-W[\w-]+)\]$')


def check(src):
    # The overlay alias header is generated by build.py; any existing build tree has it.
    r = subprocess.run([build.CLANG] + FLAGS + [str(build.ROOT / src)], capture_output=True, text=True)
    out = []
    for line in r.stderr.splitlines():
        m = LINE.match(line)
        if m and m.group(4) == '-Wint-conversion' and PTRSIZED.search(m.group(3)):
            continue  # pointer <-> BtIntPtr: same size natively, only the implicit conversion is flagged
        if m:
            path = os.path.relpath(m.group(1), build.ROOT)
            out.append((path, int(m.group(2)), m.group(4), m.group(3)))
    return src, out, r.returncode


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--top', type=int, default=15)
    args = ap.parse_args()
    srcs = [s for s in build.sources() if s.startswith('src/')]
    with ThreadPoolExecutor(os.cpu_count()) as ex:
        results = list(ex.map(check, srcs))
    rows = sorted({row for _, out, _ in results for row in out})  # headers repeat across files
    failed = [s for s, _, rc in results if rc]
    path = build.ROOT / 'build' / 'hazards64.tsv'
    with path.open('w') as f:
        f.write('file\tline\tflag\tmessage\n')
        for r in rows:
            f.write('%s\t%d\t%s\t%s\n' % r)
    print('hazards64: %d places in %d files (%d files do not compile for LP64) -> %s'
          % (len(rows), len({r[0] for r in rows}), len(failed), path))
    for flag, n in collections.Counter(r[2] for r in rows).most_common():
        print('  %6d %s' % (n, flag))
    print('  top files:')
    for file, n in collections.Counter(r[0] for r in rows).most_common(args.top):
        print('  %6d %s' % (n, file))
    failures_path = path.with_name('hazards64_failed.txt')
    failures_path.write_text(''.join(f'{src}\n' for src in failed))


if __name__ == '__main__':
    main()
