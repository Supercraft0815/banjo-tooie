#!/usr/bin/env python3
"""One entry point for the native port, with short output (for humans and agents alike).

  port.py status                 counts of every work list and checklist progress (~25 lines)
  port.py gate [--case C] [--full] [--accept] [--exe PATH]
                                 build, unit tests, replay corpus cases, compare each trace with the
                                 stored reference (build/reference/<case>.jsonl); prints PASS or the
                                 first differing retrace and field. --accept stores new references.
  port.py worklist P [--file F]  open items of a phase work list, grouped by source file:
                                 traps, xsym, calls (Phase 2), offsets, lp64 (Phase 5)

Work lists are generated by scripts and never edited by hand:
  traps  build/ilp32/traps.txt           (build.py)
  xsym   build/ilp32-xsym/xsym_*.tsv     (xsym_report.py: labels that must become one C object)
  calls  build/ilp32/widened.txt         (FixCalls: pass-through args, missing returns, void results)
  data   build/data_to_c.tsv             (data_to_c.py scan: .data modules still in asm, with the reason)
  protos build/protos.tsv                (protos.py: declarations unlike the definition: float, arity, ret, size)
  offsets build/offsets.tsv              (offsets.py scan: `*(T *)((u8 *)p + 0x14)` and similar)
  lp64   build/hazards64.tsv             (hazards64.py: pointer/int mixing on a 64-bit host)
"""
import argparse
import collections
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'build' / 'ilp32'
REF = ROOT / 'build' / 'reference'
CHECKLIST = HERE.parent / 'VARIANTE_A_CHECKLISTE.md'
TESTS = ['build_test.py', 'trace_test.py', 'save_test.py', 'inventory_test.py', 'printf_test.py', 'render_test.py']
DEF = re.compile(r'^[A-Za-z_][^;\n{}()=]*?\b(\w+)\s*\([^;{}]*\)\s*\{', re.M)
NOISE = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|^\s*#[^\n]*', re.S | re.M)


def definitions(text):
    """Names of the functions a C file defines: each `name(...) {` at brace depth 0. Comments, strings
    and preprocessor lines (and #else branches) are dropped first, so `#if`-split heads, macro-wrapped return types
    (BT_IDO_ONLY(void) BT_NATIVE_ONLY(s32) f(...)) and comments before the brace still count."""
    kept, skip = [], []  # of #if/#else, keep only the first branch so the braces balance
    for line in text.splitlines():
        d = re.match(r'\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b', line)
        if d and d.group(1).startswith('if'):
            skip.append(False)
        elif d and d.group(1) in ('elif', 'else') and skip:
            skip[-1] = True
        elif d and skip:
            skip.pop()
        elif not any(skip):
            kept.append(line)
    text = NOISE.sub(' ', '\n'.join(kept))
    out, depth = [], 0
    for m in re.finditer(r'[{}]', text):
        if m.group() == '}':
            depth = max(depth - 1, 0)
            continue
        if depth == 0:
            head = text[:m.start()].rstrip()
            if head.endswith(')'):  # walk back to the matching '(' of the parameter list
                level, i = 0, len(head) - 1
                while i >= 0:
                    level += {')': 1, '(': -1}.get(head[i], 0)
                    if level == 0:
                        break
                    i -= 1
                name = re.search(r'(\w+)\s*$', head[:i])
                if name and name.group(1) not in ('if', 'while', 'for', 'switch', 'sizeof'):
                    out.append(name.group(1))
        depth += 1
    return out


def lines(path):
    return path.read_text().splitlines() if path.exists() else []


def function_files():
    """Function name -> defining source file (game C only; native .inc files count too)."""
    out = {}
    for p in sorted((ROOT / 'src').rglob('*.[ci]*')):
        if p.suffix in ('.c', '.inc'):
            for m in DEF.finditer(p.read_text(errors='replace')):
                out.setdefault(m.group(1), str(p.relative_to(ROOT)))
    for p in sorted((ROOT / 'src').rglob('*.[ci]*')):  # heads the line regex misses (macro return types, #if heads)
        if p.suffix in ('.c', '.inc'):
            for name in definitions(p.read_text(errors='replace')):
                out.setdefault(name, str(p.relative_to(ROOT)))
    return out


def worklist(phase):
    """[(file, item)] for one phase."""
    if phase == 'traps':
        return [('?', l) for l in lines(OUT / 'traps.txt')]
    if phase == 'offsets':  # one item per remaining raw offset access (offsets.py scan)
        return [(f, kind) for f, kind, n in (l.split('\t') for l in lines(ROOT / 'build' / 'offsets.tsv')[1:])
                for _ in range(int(n))]
    if phase == 'offsets64':  # raw offsets that move on a 64-bit host: pointer reads, or after one
        import csv
        groups = collections.defaultdict(list)
        path = ROOT / 'build' / 'offsets_bases.tsv'
        for r in (csv.DictReader(path.open(), delimiter='\t') if path.exists() else []):
            isptr = r['access_type'].strip().endswith('*') or '(*)' in r['access_type']
            groups[(r['file'], r['function'], r['base'])].append((int(r['offset'], 16), isptr, r['access_type']))
        out = []
        for (f, fn, b), acc in groups.items():
            first = min((o for o, p, _ in acc if p), default=None)
            out += [(f, '%s: %s + 0x%X (%s)' % (fn, b, o, t)) for o, p, t in acc if p or (first is not None and o > first)]
        return out
    if phase == 'data':  # .data modules data_to_c.py could not move to C (the reason says what the C lacks)
        rows = [l.split('\t') for l in lines(ROOT / 'build' / 'data_to_c.tsv')[1:]]
        return [(f, '%s: %s' % (m, st)) for f, m, st in rows if st not in ('ok', 'done')]
    if phase == 'protos':  # declarations that disagree with the definition (protos.py), worst first
        order = {'float': 0, 'arity': 1, 'ret': 2, 'size': 3}
        rows = [l.split('\t') for l in lines(ROOT / 'build' / 'protos.tsv')[1:]]
        return [(w.rsplit(':', 1)[0], '%s %s: def %s, here %s (line %s)' % (k, fn, d, x, w.rsplit(':', 1)[1]))
                for fn, k, d, x, w in sorted(rows, key=lambda r: (order.get(r[1], 9), r[0]))]
    if phase == 'lp64':
        return [(f, '%s:%s %s' % (f, ln, flag)) for f, ln, flag, _ in
                (l.split('\t') for l in lines(ROOT / 'build' / 'hazards64.tsv')[1:])]
    files = function_files()
    if phase == 'calls':
        out = []
        for l in sorted(set(lines(OUT / 'widened.txt'))):
            parts = l.split()
            kind, func = (parts[0], parts[1]) if parts[0].isupper() else ('ARGS', parts[0])
            out.append((files.get(func, '?'), '%s %s' % (kind, ' '.join(parts[1:] if kind != 'ARGS' else parts))))
        return out
    if phase == 'xsym':
        out = []
        for l in lines(ROOT / 'build' / 'ilp32-xsym' / 'xsym_groups.tsv')[1:]:
            labels, funcs = l.split('\t')
            for f in funcs.split():
                out.append((files.get(f, '?'), '%s: %s' % (f, labels)))
        return out
    sys.exit('unknown work list ' + phase)


def status():
    print('build: %s' % ((OUT / 'bt_game').exists() and 'build/ilp32/bt_game' or 'none (run build.py)'))
    for phase, what in (('traps', 'function traps (Phase 0)'), ('xsym', 'cross-symbol accesses (Phase 1)'),
                        ('data', '.data modules still in asm (Phase 1)'),
                        ('calls', 'IDO call fixes left to FixCalls (Phase 2)'), ('offsets', 'raw byte-offset accesses (Phase 5)'),
                        ('offsets64', '  of these move on 64-bit (pointer or after one)'),
                        ('protos', 'declarations unlike their definition (Phase 2)'),
                        ('lp64', 'pointer/int mixes (Phase 5)')):
        items = worklist(phase)
        kinds = collections.Counter(i.split()[0] if phase in ('calls', 'protos') else '' for _, i in items)
        detail = ', '.join('%s %d' % kv for kv in kinds.most_common()) if phase in ('calls', 'protos') else ''
        print('%-6s %5d %s in %d files %s' % (phase, len(items), what, len({f for f, _ in items}),
                                             detail and '(' + detail + ')'))
    refs = sorted(p.stem for p in REF.glob('*.jsonl'))
    print('gate references: %s' % (', '.join(refs) or 'none (port.py gate --accept)'))
    phase, counts = None, collections.OrderedDict()
    for l in lines(CHECKLIST):
        m = re.match(r'## (Phase \d+)', l)
        if m:
            phase = m.group(1)
        elif phase and re.match(r'- \[[ x]\]', l):
            done, total = counts.get(phase, (0, 0))
            counts[phase] = (done + (l[3] == 'x'), total + 1)
    print('checklist: ' + ', '.join('%s %d/%d' % (p.split()[1], d, t) for p, (d, t) in counts.items()))


def run_case(exe, name, work):
    sys.path.insert(0, str(HERE))
    import corpus
    case = corpus.CASES[name]
    work.mkdir(parents=True)
    if case['flags'] is not None:
        (work / 'bt_eeprom.bin').write_bytes(
            corpus.save_editor.edit(bytes(2048), 0, [(f, True) for f in case['flags']], create=True))
    env = {k: v for k, v in os.environ.items() if not k.startswith('BT_')}
    env.update(BT_VCLOCK='1', BT_HEADLESS='1', BT_EXIT_AFTER=str(case['seconds']), **corpus.run_env(case),
               BT_TRACE=str(work / 'trace.jsonl'))
    with (work / 'run.log').open('w') as log:
        r = subprocess.run([str(exe), str(ROOT / 'baserom.us.z64')], cwd=work, env=env, stdout=log, stderr=log,
                           timeout=3600)
    return r.returncode


def gate(cases, accept, exe=None):
    if exe:  # compare a given (diagnostic) build with the references; no build, no tests
        return replay(cases, accept, exe)
    r = subprocess.run([sys.executable, str(HERE / 'build.py')], capture_output=True, text=True)
    if r.returncode:
        print('FAIL build:\n' + (r.stdout + r.stderr)[-3000:])
        return 1
    print(r.stdout.strip().splitlines()[-2])
    for t in TESTS:
        r = subprocess.run([sys.executable, str(HERE / 'tests' / t)], capture_output=True, text=True, cwd=ROOT)
        if r.returncode:
            print('FAIL test %s:\n%s' % (t, (r.stdout + r.stderr)[-2000:]))
            return 1
    print('tests: %d passed' % len(TESTS))
    return replay(cases, accept, OUT / 'bt_game')


def replay(cases, accept, built):
    sys.path.insert(0, str(HERE))
    import trace_tools
    work = Path(tempfile.mkdtemp(prefix='gate-', dir=ROOT / 'build'))
    exe = work / 'bt_game'
    shutil.copy2(built, exe)  # a rebuild during the run must not change the binary
    failed = 0
    import concurrent.futures  # cases are separate processes and dirs on the virtual clock
    with concurrent.futures.ThreadPoolExecutor(len(cases)) as pool:
        codes = list(pool.map(lambda name: run_case(exe, name, work / name), cases))
    for name, rc in zip(cases, codes):
        trace = work / name / 'trace.jsonl'
        if rc:
            print('FAIL %s: exit %d, log %s' % (name, rc, work / name / 'run.log'))
            failed = 1
            continue
        ref = REF / (name + '.jsonl')
        if accept or not ref.exists():
            REF.mkdir(parents=True, exist_ok=True)
            shutil.copy2(trace, ref)
            print('%s: reference stored (%s)' % (name, ref))
            continue
        with ref.open() as a, trace.open() as b:
            import contextlib
            import io
            buf = io.StringIO()
            with contextlib.redirect_stdout(buf):
                rc = trace_tools.compare(a, b, cross_build=True)
        print('%s %s: %s' % ('PASS' if rc == 0 else 'FAIL', name, buf.getvalue().strip()))
        failed |= rc
    if not failed:
        shutil.rmtree(work)
    return failed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('status')
    g = sub.add_parser('gate')
    g.add_argument('--case', action='append', choices=['intro', 'new-game', 'edited-save', 'worlds'])
    g.add_argument('--full', action='store_true', help='all cases (about 7 minutes)')
    g.add_argument('--accept', action='store_true')
    g.add_argument('--exe', type=Path, help='replay this executable instead of building (e.g. build/ilp32-shift/bt_game)')
    w = sub.add_parser('worklist')
    w.add_argument('phase', choices=['traps', 'xsym', 'data', 'calls', 'protos', 'offsets', 'offsets64', 'lp64'])
    w.add_argument('--file', help='only this source file')
    args = ap.parse_args()
    if args.cmd == 'status':
        status()
    elif args.cmd == 'gate':
        cases = ['intro', 'new-game', 'edited-save', 'worlds'] if args.full else (args.case or ['intro'])
        return gate(cases, args.accept, args.exe and args.exe.resolve())
    else:
        by_file = collections.defaultdict(list)
        for f, item in worklist(args.phase):
            if not args.file or f == args.file:
                by_file[f].append(item)
        for f in sorted(by_file, key=lambda f: -len(by_file[f])):
            print('%s (%d)' % (f, len(by_file[f])))
            for item in by_file[f]:
                print('  ' + item)
    return 0


if __name__ == '__main__':
    sys.exit(main())
