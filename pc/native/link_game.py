#!/usr/bin/env python3
"""Builds bt_native_game and generates traps for every symbol that is still missing.

Usage: pc/native/link_game.py [build/native]

Links once without traps, collects the undefined symbols from the linker and writes
<build>/native/generated/unported.c, then links again:
- functions become bodies that call bt_unported("name") and abort;
- .bss symbols become zeroed storage (zero is their real initial value), sized
  generously because host structures with pointers are larger than on the N64;
- initialized data and linker-script symbols go to a page-protected area, so the
  first access reports the symbol (see platform/traps.c).
"""
import re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
build = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build/native"
traps = build / "native/generated/unported.c"
SIZES = {".word": 4, ".float": 4, ".half": 2, ".short": 2, ".byte": 1, ".double": 8, ".dword": 8}


def asm_labels():
    """Maps every data label in the splat output and handwritten bss files to (kind, N64 size)."""
    labels = {}
    files = list((ROOT / "asm/data").rglob("*.s")) + list((ROOT / "src").rglob("*.s"))
    for path in files:
        kind = "bss" if ".bss" in path.name or "bss" in path.name else "data"
        cur, size, cur_kind = None, 0, kind
        for line in path.read_text(errors="replace").splitlines():
            line = re.sub(r"/\*.*?\*/", "", line).strip()
            m = re.match(r"(?:dlabel|glabel)\s+(\w+)", line)
            if m:
                if cur and cur_kind != "func": labels.setdefault(cur, (cur_kind, size))
                cur_kind = kind
                cur, size = m.group(1), 0
                continue
            if line.startswith(".section") or line in (".text", ".data", ".bss"):
                kind = "func" if ".text" in line else "bss" if ".bss" in line else "data"
            if not cur:
                continue
            m = re.match(r"(\.\w+)\s*(.*)", line)
            if not m:
                continue
            op, rest = m.groups()
            if op in SIZES:
                size += SIZES[op] * (rest.count(",") + 1)
            elif op == ".space":
                size += int(rest.split(",")[0], 0)
            elif op in (".asciz", ".ascii"):
                size += len(bytes(rest.strip()[1:-1], "utf-8").decode("unicode_escape")) + (op == ".asciz")
        if cur and cur_kind != "func": labels.setdefault(cur, (cur_kind, size))
    return labels


def build_game():
    r = subprocess.run(["cmake", "--build", str(build), "--target", "bt_native_game", "--parallel"],
                       capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def undefined(log):
    names = re.findall(r'^\s+"_?(\w+)", referenced from:', log, re.M)  # Apple ld
    names += re.findall(r"undefined reference to `(\w+)'", log)          # GNU ld
    return sorted(set(names))


def write_traps(names, labels):
    linker = re.compile(r"_(ROM_START|ROM_END|VRAM|VRAM_END|BSS_START|BSS_END|TEXT_START|TEXT_END|"
                        r"DATA_START|DATA_END|RODATA_START|RODATA_END)$")
    out = ["// Generated by pc/native/link_game.py: symbols that are not ported yet.",
           '#include "native_traps.h"', ""]
    funcs, bss, data = [], [], []
    for n in names:
        kind, size = labels.get(n, ("linker" if linker.search(n) else "func", 0))
        (funcs if kind == "func" else bss if kind == "bss" else data).append((n, max(size, 16)))
    for n, _ in funcs:
        out.append(f'void {n}(void) {{ bt_unported("{n}"); }}')
    for n, size in bss:
        out.append(f"__attribute__((aligned(16))) char {n}[{size * 2 + 16}];")
    # One assembly section without .subsections_via_symbols keeps the order, so the
    # data really lies between the two page-aligned markers.
    # shortcut: Mach-O syntax only; add an ELF/COFF variant when building on Linux/Windows.
    asm = [".section __DATA,__bttrap", ".p2align 14", ".globl _bt_trap_area_start",
           "_bt_trap_area_start:", ".space 16384"]
    for n, size in data:
        asm += [".p2align 4", f".globl _{n}", f"_{n}:", f".space {size}"]
    asm += [".p2align 14", ".globl _bt_trap_area_end", "_bt_trap_area_end:", ".space 16384", ""]
    traps.with_suffix(".s").write_text("\n".join(asm))
    out += [f"extern char {n}[];" for n, _ in data]
    out.append("const BtTrapData bt_trap_data[] = {")
    out += [f'    {{"{n}", {n}, {size}}},' for n, size in data]
    out += ["    {0, 0, 0},", "};", ""]
    traps.write_text("\n".join(out))
    return len(funcs), len(bss), len(data)


traps.parent.mkdir(parents=True, exist_ok=True)
write_traps([], {})
rc, log = build_game()
missing = undefined(log)
if rc != 0 and not missing:
    sys.exit(log[-6000:])
counts = write_traps(missing, asm_labels())
rc, log = build_game()
if rc != 0:
    sys.exit(log[-6000:])
print("bt_native_game linked; traps: %d functions, %d bss, %d data" % counts)
