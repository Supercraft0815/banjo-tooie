#!/usr/bin/env python3
"""Prove what "100% decompiled" means for this repo. Run through `make complete`.

Fails unless the built ROM is byte-identical to the original, no C file imports
assembly, and every byte of code comes from C, tracked handwritten assembly, libultra,
RSP microcode or tables built from tracked files. Data is reported but not gated: most of it is still generated by splat.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

SECTIONS = (".text", ".rodata", ".data", ".bss")
# " .text  0x80000400  0x50 build/us/src/boot/1050.c.o"; long section names wrap onto the next line.
MAP_LINE = re.compile(r"^ (\.\w+)\s+0x[0-9a-fA-F]+\s+0x([0-9a-fA-F]+)\s+(\S+)$")
IMPORT = re.compile(r"^\s*(#pragma\s+GLOBAL_ASM|INCLUDE_ASM|INCLUDE_RODATA)", re.M)
# Nintendo's RSP microcode blobs: code for the RCP, shipped in the SDK as binaries, not game source.
RSP_MICROCODE = ("n_aspMain", "rspboot", "gspF3DEX2.NoN.fifo", "gspF3DEX2.fifo", "gspL3DEX2.fifo")


def origin(path: str) -> str:
    if ".a(" in path or path.endswith(".a"):
        return "libultra"
    path = path.split("build/us/", 1)[-1]
    if path.startswith("src/") and path.endswith(".c.o"):
        return "c"
    if path.startswith("src/") and path.endswith(".s.o"):
        return "handwritten"
    if any(path.startswith(f"asm/data/core1/{name}.") for name in RSP_MICROCODE):
        return "rsp-microcode"
    # Built from the tracked overlays.us.toml by tools/syscall_builder.
    if path.startswith("assets/") or path == "asm/core2/overlay_syscalls.s.o":
        return "built-from-tables"
    return "generated"


def section_sizes(map_text: str) -> dict[str, Counter]:
    sizes = {section: Counter() for section in SECTIONS}
    lines = map_text.splitlines()
    for i, line in enumerate(lines):
        # A long section name pushes address, size and path onto the next line.
        if re.fullmatch(r" \.\w+", line) and i + 1 < len(lines):
            line = line + " " + lines[i + 1].strip()
        match = MAP_LINE.match(line)
        if match and match[1] in sizes and int(match[2], 16) and "build/" in match[3]:
            sizes[match[1]][origin(match[3])] += int(match[2], 16)
    return sizes


def asm_imports(src: Path) -> list[str]:
    return [str(path) for path in sorted(src.rglob("*.c")) if IMPORT.search(path.read_text(errors="replace"))]


def rom_matches(built: bytes, original: bytes) -> bool:
    # The original cartridge image is the built ROM followed by 0xFF padding.
    tail = original[len(built):]
    return len(built) <= len(original) and original[: len(built)] == built and not tail.strip(b"\xff")


def self_test() -> None:
    sample = (" .text          0x80000450       0x10 build/us/src/boot/a.c.o\n"
              " .text          0x80000460       0x20 build/us/src/boot/b.s.o\n"
              " .text          0x80000480       0x30 build/us/libultra_rom.a(x.o)\n"
              " .data          0x80000500       0x40 build/us/asm/data/boot/x.data.s.o\n"
              " .rodata\n                0x80000540       0x50 build/us/src/boot/a.c.o\n"
              " .text          0x80000600        0x0 build/us/asm/empty.s.o\n"
              " .text          0x80000610       0x60 build/us/asm/data/core1/rspboot.s.o\n")
    sizes = section_sizes(sample)
    assert sizes[".text"] == {"c": 0x10, "handwritten": 0x20, "libultra": 0x30, "rsp-microcode": 0x60}, sizes
    assert sizes[".data"] == {"generated": 0x40}, sizes
    assert sizes[".rodata"] == {"c": 0x50}, sizes
    assert rom_matches(b"ab", b"ab\xff\xff") and not rom_matches(b"ab", b"ac\xff") and not rom_matches(b"ab", b"ab\x00")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, default=Path("build/us"))
    args = parser.parse_args()
    self_test()

    failures = []
    built = (args.build / "banjotooie.z64").read_bytes()
    if not rom_matches(built, Path("baserom.us.z64").read_bytes()):
        failures.append("compressed ROM differs from baserom.us.z64")
    uncompressed = (args.build / "banjotooie_decompressed.z64").read_bytes()
    if uncompressed != Path("decompressed.us.z64").read_bytes():
        failures.append("decompressed ROM differs from decompressed.us.z64")

    imports = asm_imports(Path("src"))
    if imports:
        failures.append(f"{len(imports)} C files still import assembly, first: {imports[0]}")

    sizes = section_sizes((args.build / "banjotooie_decompressed.map").read_text())
    if sizes[".text"]["generated"]:
        failures.append(f"{sizes['.text']['generated']:#x} bytes of code are still generated by splat")

    for section in SECTIONS:
        total = sum(sizes[section].values())
        parts = ", ".join(f"{name} {size:#x} ({100 * size / total:.2f}%)" for name, size in sizes[section].most_common())
        print(f"{section:8} {total:#10x}  {parts}")

    for failure in failures:
        print(f"FAIL: {failure}", file=sys.stderr)
    if not failures:
        print("COMPLETE: ROM byte-identical, no assembly imports, no generated code.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
